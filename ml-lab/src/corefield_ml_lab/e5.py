"""Preregistered E5 episode-level conformal experiment.

This module keeps the E5 orchestration separate from the neural experiments.
It fits the frozen nonlinear least-squares estimator once, then treats each
eight-hour load episode as one independent scalar observation.  Test truth is
only generated by :func:`run_e5_primary`, after the write-once run sentinel has
been claimed.

Absolute temperatures are in degrees Celsius, conformity scores and interval
widths are in kelvin, time is in seconds, and load is per unit.  Expected
unbounded limits are represented by ``None`` plus an explicit status in JSON;
no JSON artifact contains IEEE NaN or infinity values.
"""

